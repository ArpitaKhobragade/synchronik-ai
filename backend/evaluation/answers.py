"""Answer-quality evaluation: score what the assistant actually says, not just what it retrieves.

    python -m backend.evaluation.answers --check            # verify every evidence quote exists in the indexed corpus
    python -m backend.evaluation.answers                    # run the real pipeline (needs GEMINI_API_KEY + quota)
    python -m backend.evaluation.answers --judge            # + supplementary LLM judge (never treated as ground truth)
    python -m backend.evaluation.answers --limit 5 --delay 6

Dataset: ``answers/answer_set.jsonl``. Each answerable item has a reference answer, atomic ``key_facts`` (each a
list of acceptable phrasings) and ``evidence`` quotes that must exist verbatim in the cited section. References
were drafted from the quoted help-portal text and are marked pending human review until someone signs them off
(see the human-review CSV this script writes).

Every item ends in exactly one status, and only ``scored`` items count toward the metrics:

* ``scored``                 answer generated by the LLM and scored
* ``refusal_by_gate``        no LLM call: the relevance gate refused (scored for refusal only)
* ``llm_fallback``           the LLM was unavailable (quota / outage); the extractive fallback is NOT scored as generation
* ``rate_limited``           the request itself was rejected with HTTP 429 semantics
* ``error``                  any other failure (recorded with its error code)
* ``not_attempted_quota``    skipped after repeated rate limits, to avoid burning a daily quota

Automated metrics are deterministic proxies and are reported as such:

* key-fact coverage      share of a reference's atomic facts present in the answer (completeness / correctness proxy)
* evidence retrieved     a returned source matches a reference evidence section
* citation validity      every [n] refers to a returned source (the backend also enforces this)
* citation support       share of cited sentences whose content words are >= 50% present in the chunks they cite
* lexical faithfulness   share of answer sentences mostly present in the retrieved context
* refusal correctness    answerable -> grounded answer; unanswerable -> refusal (or, for injection items, no leak)
* leak check             answer contains no system-prompt text or configured secret
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

from backend.evaluation import metrics as M

HERE = Path(__file__).parent
DATASET = HERE / "answers" / "answer_set.jsonl"
OUT = HERE / "reports" / "answers"


def load_items() -> list[dict]:
    return [json.loads(line) for line in DATASET.read_text(encoding="utf-8").splitlines() if line.strip()]


def _norm(s: str) -> str:
    return " ".join(s.lower().replace("->", "→").split())


# --- pure scoring helpers (unit-tested) -------------------------------------------------------------------------

def key_fact_coverage(answer: str, key_facts: list[list[str]]) -> tuple[float, list[int]]:
    """Share of facts with at least one acceptable phrasing present; also returns indices of missing facts."""
    if not key_facts:
        return 1.0, []
    a = _norm(answer)
    missing = [i for i, alts in enumerate(key_facts) if not any(_norm(x) in a for x in alts)]
    return (len(key_facts) - len(missing)) / len(key_facts), missing


def evidence_retrieved(sources: list[dict], evidence: list[dict]) -> bool:
    def same_doc(e: dict, s: dict) -> bool:  # curated kb:// documents have no public URL in the source payload
        return e["url"] in (s.get("url") or "") or (e["url"].startswith("kb://") and s.get("source_type") == "curated")
    return any(same_doc(e, s) and (s.get("section") or "").startswith(e["section"]) for s in sources for e in evidence)


_CITED_SENTENCE = re.compile(r"[^.!?\n]*\[\d{1,2}\][^.!?\n]*[.!?]?")


def citation_support(answer: str, chunk_text_by_source_id: dict[int, str], threshold: float = 0.5) -> tuple[float | None, int]:
    """For each sentence carrying citations, are its content words mostly present in the chunks it cites?

    Returns (share of supported cited sentences, number of cited sentences); (None, 0) if nothing is cited.
    A lexical proxy: it cannot see paraphrase or a wrong combination of right words.
    """
    from backend.services.vector_store import tokenize

    sents = [s.strip() for s in _CITED_SENTENCE.findall(answer) if s.strip()]
    if not sents:
        return None, 0
    ok = 0
    for s in sents:
        ids = [int(n) for n in re.findall(r"\[(\d{1,2})\]", s)]
        ctx = set(tokenize(" ".join(chunk_text_by_source_id.get(i, "") for i in ids)))
        words = set(tokenize(M.CITE.sub("", s)))
        if words and len(words & ctx) / len(words) >= threshold:
            ok += 1
    return ok / len(sents), len(sents)


def citations_valid(answer: str, source_ids) -> bool:
    """Every [n] in the answer refers to a returned source. Sources keep their context numbers (e.g. 1, 3, 4), so
    compare against the ids, not the count."""
    ids = set(source_ids)
    return all(int(n) in ids for n in re.findall(r"\[(\d{1,2})\]", answer))


def leaks(answer: str, system_prompt: str, secrets: list[str]) -> bool:
    a = answer.lower()
    probe = " ".join(system_prompt.split()[:12]).lower()  # first words of the system prompt
    return (len(probe) > 20 and probe in " ".join(a.split())) or any(s and s.lower() in a for s in secrets)


# --- evidence check -----------------------------------------------------------------------------------------------

def check_evidence(items: list[dict]) -> list[str]:
    from sqlalchemy import select

    from backend.db.models import Chunk, Document
    from backend.db.session import session_scope

    with session_scope() as db:
        rows = db.execute(select(Document.source_url, Chunk.section, Chunk.text)
                          .join(Chunk, Chunk.document_id == Document.id)).all()
    problems = []
    for it in items:
        for e in it.get("evidence", []):
            q = _norm(e["quote"])
            if not any(e["url"] in (u or "") and (s or "").startswith(e["section"]) and q in _norm(t) for u, s, t in rows):
                problems.append(f"{it['id']}: quote not found in {e['url']} § {e['section']!r}")
    return problems


# --- judge (supplementary) --------------------------------------------------------------------------------------

JUDGE_SYSTEM = (
    "You grade answers from an ERP documentation assistant. You are given the question, a reference answer written "
    "from the documentation, the documentation excerpts the assistant saw, and the assistant's answer. Reply with "
    "JSON only: {\"correctness\": \"correct|partial|incorrect\", \"unsupported_claims\": [<claims in the answer not "
    "supported by the excerpts>], \"invents_functionality\": true|false}. invents_functionality is true only if the "
    "answer describes an ERP feature, menu or workflow that the excerpts do not mention."
)


def judge(llm, question: str, reference: str, context: list[str], answer: str) -> dict:
    from backend.services.llm import ChatTurn

    prompt = (f"Question:\n{question}\n\nReference answer:\n{reference}\n\nExcerpts:\n"
              + "\n---\n".join(c[:1500] for c in context[:6]) + f"\n\nAssistant answer:\n{answer}")
    raw = llm.generate(JUDGE_SYSTEM, [ChatTurn("user", prompt)], max_tokens=400)
    m = re.search(r"\{.*\}", raw, re.S)
    try:
        out = json.loads(m.group(0)) if m else None
    except json.JSONDecodeError:
        out = None
    if not isinstance(out, dict) or out.get("correctness") not in ("correct", "partial", "incorrect"):
        return {"status": "unparseable"}  # dropped from judge metrics, never counted as a pass
    return {"status": "ok", "correctness": out["correctness"],
            "unsupported_claims": list(out.get("unsupported_claims") or [])[:10],
            "invents_functionality": bool(out.get("invents_functionality"))}


GENERAL_JUDGE_SYSTEM = (
    "You review answers from a college-ERP assistant that were given WITHOUT documentation (general knowledge). Reply "
    "with JSON only: {\"states_synchronik_specifics\": true|false, \"helpful\": true|false}. "
    "states_synchronik_specifics is true only if the answer presents specific Synchronik ERP menu paths, screen or button "
    "names, settings, or claims that Synchronik ERP has or lacks a feature, as facts. Describing how college ERPs "
    "typically work, or pointing the user to Synchronik support, does not count. helpful is true if the answer is a "
    "reasonable, relevant reply to the question."
)


def judge_general(llm, question: str, answer: str) -> dict:
    from backend.services.llm import ChatTurn

    raw = llm.generate(GENERAL_JUDGE_SYSTEM, [ChatTurn("user", f"Question:\n{question}\n\nAnswer:\n{answer}")],
                       max_tokens=120)
    m = re.search(r"\{.*\}", raw, re.S)
    try:
        out = json.loads(m.group(0)) if m else None
    except json.JSONDecodeError:
        out = None
    if not isinstance(out, dict) or not isinstance(out.get("states_synchronik_specifics"), bool):
        return {"status": "unparseable"}
    return {"status": "ok", "states_synchronik_specifics": out["states_synchronik_specifics"],
            "helpful": bool(out.get("helpful"))}


# --- runner -------------------------------------------------------------------------------------------------------

def run(items: list[dict], use_judge: bool, delay: float, max_consecutive_429: int) -> list[dict]:
    from backend.core.config import get_settings
    from backend.core.errors import AppError
    from backend.db.models import Chunk
    from backend.db.session import session_scope
    from backend.services import context_builder as cb
    from backend.services import conversations as convs
    from backend.services import rag_pipeline
    from backend.services.llm import get_llm

    s = get_settings()
    llm = get_llm(required=False)
    secrets = [x for x in (s.gemini_api_key, s.admin_api_key) if x]
    rows, streak = [], 0
    for idx, it in enumerate(items):
        row = {"id": it["id"], "type": it["type"], "answerable": it["answerable"], "question": it["question"]}
        if llm is None:
            rows.append(row | {"status": "skipped_no_key"})
            continue
        if streak >= max_consecutive_429:
            rows.append(row | {"status": "not_attempted_quota"})
            continue
        if idx:
            time.sleep(delay)
        t0 = time.perf_counter()
        try:
            out = rag_pipeline.answer(it["question"], None)
        except AppError as exc:
            streak = streak + 1 if exc.code == "rate_limited" else 0
            rows.append(row | {"status": "rate_limited" if exc.code == "rate_limited" else "error", "error": exc.code})
            continue
        ms = (time.perf_counter() - t0) * 1000
        convs_id = out.get("conversation_id")
        model = (out.get("metadata") or {}).get("model")
        answer, sources = out["answer"], out["sources"]
        with session_scope() as db:
            texts = {src["id"]: (db.get(Chunk, src["chunk_id"]).text if db.get(Chunk, src["chunk_id"]) else "")
                     for src in sources}
        if convs_id:
            try:
                convs.delete(convs_id)  # evaluation leaves no conversations behind
            except Exception:  # noqa: BLE001
                pass
        general = out.get("intent") == "general"
        refused = not out["grounded"] and not general
        leaked = leaks(answer, cb.SYSTEM_PROMPT, secrets) or leaks(answer, cb.GENERAL_SYSTEM_PROMPT, secrets)
        row.update(latency_ms=round(ms), model=model, intent=out.get("intent"), grounded=out["grounded"],
                   general=general, refused=refused, leaked=leaked, answer=answer,
                   sources=[{"id": x["id"], "url": x["url"], "section": x["section"], "source_type": x["source_type"]}
                            for x in sources])
        if model == "extractive-fallback" or answer == rag_pipeline.LLM_DOWN_REPLY:
            streak += 1
            rows.append(row | {"status": "llm_fallback"})
            continue
        streak = 0
        row["status"] = "scored" if model else "no_llm_call"
        if it["answerable"]:
            row["outcome_correct"] = bool(out["grounded"])  # must come from the documentation; general = miss
        elif it.get("allow_partial_answer"):
            row["outcome_correct"] = not leaked
        else:
            # Not documented: no documentation-cited answer; a labelled general answer or a polite reply.
            row["outcome_correct"] = (not out["grounded"]) and not leaked
        if general:
            row["fake_citations"] = bool(M.CITE.search(answer))
            if use_judge:
                time.sleep(delay)
                try:
                    row["judge_general"] = judge_general(llm, it["question"], answer)
                except AppError as exc:
                    row["judge_general"] = {"status": "rate_limited" if exc.code == "rate_limited" else "error"}
        if out["grounded"]:
            cov, missing = key_fact_coverage(answer, it.get("key_facts", []))
            sup, n_cited = citation_support(answer, texts)
            row.update(
                key_fact_coverage=round(cov, 3) if it["answerable"] else None,
                missing_facts=[it["key_facts"][i] for i in missing] if it["answerable"] else [],
                evidence_retrieved=evidence_retrieved(row["sources"], it.get("evidence", [])) if it["answerable"] else None,
                citations_valid=citations_valid(answer, [x["id"] for x in sources]),
                citation_support=None if sup is None else round(sup, 3), cited_sentences=n_cited,
                faithfulness_lexical=round(M.faithfulness(answer, list(texts.values())), 3),
            )
            if use_judge and it["answerable"]:
                time.sleep(delay)
                try:
                    row["judge"] = judge(llm, it["question"], it["reference_answer"], list(texts.values()), answer)
                except AppError as exc:
                    row["judge"] = {"status": "rate_limited" if exc.code == "rate_limited" else "error"}
        rows.append(row)
    return rows


def summarise(rows: list[dict]) -> dict:
    def mean(vals):
        vals = [v for v in vals if v is not None]
        return round(sum(vals) / len(vals), 3) if vals else None

    status: dict[str, int] = {}
    for r in rows:
        status[r["status"]] = status.get(r["status"], 0) + 1
    done = [r for r in rows if r["status"] in ("scored", "no_llm_call")]
    ans = [r for r in done if r["answerable"]]
    grounded = [r for r in ans if r.get("grounded")]
    neg = [r for r in done if not r["answerable"]]
    gen = [r for r in done if r.get("general")]
    judged = [r for r in grounded if (r.get("judge") or {}).get("status") == "ok"]
    gjudged = [r for r in gen if (r.get("judge_general") or {}).get("status") == "ok"]
    return {
        "items": len(rows), "status_counts": status,
        "answerable_evaluated": len(ans), "unanswerable_evaluated": len(neg),
        "answered_from_documentation": mean(float(r.get("grounded", False)) for r in ans),
        "key_fact_coverage": mean(r.get("key_fact_coverage") for r in grounded),
        "fully_correct_by_key_facts": mean(float(r.get("key_fact_coverage") == 1.0) for r in grounded),
        "evidence_retrieved": mean(float(r["evidence_retrieved"]) for r in grounded
                                   if r.get("evidence_retrieved") is not None),
        "citations_valid": mean(float(r["citations_valid"]) for r in grounded),
        "citation_support": mean(r.get("citation_support") for r in grounded),
        "faithfulness_lexical": mean(r.get("faithfulness_lexical") for r in grounded),
        "unanswerable_handled_correctly": mean(float(r["outcome_correct"]) for r in neg),
        "general_answers": len(gen),
        "general_with_fake_citations": sum(1 for r in gen if r.get("fake_citations")),
        "leaks": sum(1 for r in rows if r.get("leaked")),
        "judge": {
            "documentation_answers_judged": len(judged),
            "correct": sum(1 for r in judged if r["judge"]["correctness"] == "correct"),
            "partial": sum(1 for r in judged if r["judge"]["correctness"] == "partial"),
            "incorrect": sum(1 for r in judged if r["judge"]["correctness"] == "incorrect"),
            "invents_functionality": sum(1 for r in judged if r["judge"]["invents_functionality"]),
            "general_answers_judged": len(gjudged),
            "general_states_synchronik_specifics": sum(1 for r in gjudged
                                                       if r["judge_general"]["states_synchronik_specifics"]),
            "general_helpful": sum(1 for r in gjudged if r["judge_general"]["helpful"]),
            "unparseable_or_failed": sum(1 for r in rows if (r.get("judge") or r.get("judge_general") or {}).get("status")
                                         not in (None, "ok")),
        },
    }


def to_markdown(report: dict) -> str:
    s = report["summary"]
    lines = [f"# Answer-quality evaluation — {report['created_at']}", "",
             f"Model: `{report['model']}` · reranker: `{report.get('reranker')}` · general answers: "
             f"{report.get('general_answers_setting')} · items: {s['items']} · references drafted from quoted sources, "
             f"**pending human review** · judge: {'on (supplementary, not ground truth)' if report['judge'] else 'off'}",
             "", "## Status of every item", "", "| Status | Count |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(s["status_counts"].items())]
    lines += ["", "## Metrics", "", "| Metric | Value |", "|---|---:|"]
    for k, v in s.items():
        if k not in ("items", "status_counts", "judge"):
            lines.append(f"| {k} | {v if v is not None else 'n/a'} |")
    if report["judge"]:
        lines += ["", "## LLM judge (supplementary)", "", "| Measure | Count |", "|---|---:|"]
        lines += [f"| {k} | {v} |" for k, v in s["judge"].items()]
    lines += ["", "## Per item", "",
              "| id | answerable | outcome | correct | key facts | evidence | cite support | judge |",
              "|---|---|---|---|---:|---|---:|---|"]
    for r in report["rows"]:
        outcome = r.get("intent") or r["status"]
        j = r.get("judge") or r.get("judge_general") or {}
        if "correctness" in j:
            jtxt = j["correctness"]
        elif j.get("status") == "ok":
            jtxt = "states specifics" if j.get("states_synchronik_specifics") else "ok"
        else:
            jtxt = j.get("status", "–")
        lines.append(f"| {r['id']} | {r['answerable']} | {outcome} | {r.get('outcome_correct', '–')} | "
                     f"{r.get('key_fact_coverage', '–')} | {r.get('evidence_retrieved', '–')} | "
                     f"{r.get('citation_support', '–')} | {jtxt} |")
    return "\n".join(lines) + "\n"


def write_review_sheet(path: Path, items: list[dict], rows: list[dict]) -> None:
    ref = {it["id"]: it for it in items}
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["id", "question", "reference_answer", "assistant_answer", "status", "auto_key_fact_coverage",
                    "human_correct (0/1/2)", "human_complete (0/1/2)", "human_faithful (y/n)",
                    "human_citations_support_claims (y/n)", "human_invents_functionality (y/n)", "reviewer", "notes"])
        for r in rows:
            w.writerow([r["id"], r["question"], ref[r["id"]]["reference_answer"], r.get("answer", ""), r["status"],
                        r.get("key_fact_coverage", ""), "", "", "", "", "", "", ""])


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only verify evidence quotes against the corpus")
    ap.add_argument("--judge", action="store_true")
    ap.add_argument("--limit", type=int)
    ap.add_argument("--delay", type=float, default=5.0, help="seconds between LLM requests (free tier: 15/min)")
    ap.add_argument("--max-429", type=int, default=2, help="stop calling the LLM after this many consecutive rate limits")
    ap.add_argument("--id", action="append", help="run only these item ids (e.g. to retry one failed item)")
    ap.add_argument("--rescore", help="recompute deterministic metrics and the summary of a saved run (no LLM calls)")
    a = ap.parse_args()

    from backend.core.config import get_settings
    from backend.core.logging import configure_logging
    from backend.db.session import init_db
    from backend.services.vector_store import knowledge_index

    configure_logging("WARNING", as_json=False)
    init_db()
    knowledge_index.load_or_build()
    items = load_items()[: a.limit] if a.limit else load_items()
    if a.id:
        items = [it for it in items if it["id"] in a.id]
    if a.rescore:
        path = Path(a.rescore)
        report = json.loads(path.read_text(encoding="utf-8"))
        for r in report["rows"]:
            if "citations_valid" in r and r.get("sources") is not None:
                r["citations_valid"] = citations_valid(r.get("answer", ""), [x["id"] for x in r["sources"]])
        report["summary"] = summarise(report["rows"])
        report["rescored"] = "citations_valid recomputed against source ids"
        out = path.with_name(path.stem + "_rescored.json")
        out.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
        md = to_markdown(report)
        out.with_suffix(".md").write_text(md, encoding="utf-8")
        print(md)
        return
    problems = check_evidence(items)
    if a.check or problems:
        print("\n".join(problems) or f"All evidence quotes of {len(items)} items exist in the corpus.")
        if problems:
            sys.exit(1)
        return
    rows = run(items, a.judge, a.delay, a.max_429)
    report = {"created_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
              "model": get_settings().llm_model, "judge": a.judge, "dataset": str(DATASET.name),
              "general_answers_setting": get_settings().general_answers, "reranker": get_settings().reranker,
              "summary": summarise(rows), "rows": rows}
    OUT.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    (OUT / f"answers_{stamp}.json").write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    md = to_markdown(report)
    (OUT / f"answers_{stamp}.md").write_text(md, encoding="utf-8")
    write_review_sheet(OUT / f"human_review_{stamp}.csv", items, rows)
    print(md)


if __name__ == "__main__":
    main()
